const availableComponentsByType = new Map(
  availableComponents.map((component) => [component.type, component]),
);

if (availableComponentsByType.size !== availableComponents.length) {
  throw new Error("Duplicate component type detected in availableComponents");
}

const invalidViewComponents = availableComponents.filter(
  (component) =>
    component.viewCategory &&
    (!component.description || !Array.isArray(component.keywords)),
);

if (invalidViewComponents.length > 0) {
  throw new Error(
    `Incomplete view metadata for component types: ${invalidViewComponents
      .map((component) => component.type)
      .join(", ")}`,
  );
}

export const getComponentTitle = (type: string) => {
  const component = availableComponentsByType.get(type);
  return component ? (component.title ?? component.displayName) : undefined;
};
